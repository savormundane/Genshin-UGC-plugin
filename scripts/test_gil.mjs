import assert from 'node:assert/strict';
import {encode,parse,container,inspect,replaceLua} from './gil-toolkit.mjs';
const text=Buffer.from('function OnInit() end\n');
const entry=encode([{n:3,w:2,value:Buffer.from('example.lua')},{n:5,w:2,value:text},{n:77,w:2,value:Buffer.from([0,1,2,255])}]);
const payload=encode([{n:90,w:0,value:18446744073709551615n},{n:50,w:2,value:encode([{n:1,w:2,value:entry}])},{n:91,w:2,value:Buffer.from('unknown')}]);
const header=Buffer.alloc(20);[payload.length+20,1,806,2,payload.length].forEach((v,i)=>header.writeUInt32BE(v,i*4));
const trailer=Buffer.from([0,0,6,121]);const file=Buffer.concat([header,payload,trailer]);
assert.equal(inspect(file).roundtripByteIdentical,true);
const changed=replaceLua(file,'example.lua',Buffer.from('function OnInit() print(1) end\n'));
const before=container(file),after=container(changed);
assert.equal(before.fields[0].raw.equals(after.fields[0].raw),true);
assert.equal(before.fields[2].raw.equals(after.fields[2].raw),true);
assert.deepEqual(before.header.slice(1,4),after.header.slice(1,4));
assert.equal(parse(parse(after.fields[1].value)[0].value).find(f=>f.n===77).value.equals(Buffer.from([0,1,2,255])),true);
const unknownHeader = Buffer.from(file);
unknownHeader.writeUInt32BE(2, 4);
assert.equal(inspect(unknownHeader).roundtripByteIdentical, true);
assert.throws(() => replaceLua(unknownHeader, 'example.lua', text), /已校准的 GIL/);
assert.throws(()=>replaceLua(file,'absent.lua',text));
assert.throws(()=>container(file.subarray(0,-1)));
assert.throws(()=>parse(Buffer.from([10,5,1])));
assert.throws(()=>parse(Buffer.from([9,1])));
assert.throws(()=>parse(Buffer.from([8,...Array(9).fill(255),2])));
console.log('PASS: roundtrip, Lua replacement, unknown fields, metadata, uint64 and invalid-input handling');
